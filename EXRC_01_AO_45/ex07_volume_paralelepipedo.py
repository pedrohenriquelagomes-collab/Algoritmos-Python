#Receba os valores do comprimento, largura e altura de um paralelepípedo. Calcule e mostre seu volume.

comprimento = int(input("Digite o valor do comprimento: "))
largura = int(input("Digite o valor da largura: "))
altura = int(input("Digite o valor do altura: "))

volume = comprimento * largura * altura

print(f"O volume do paralelepípedo é: {volume}")